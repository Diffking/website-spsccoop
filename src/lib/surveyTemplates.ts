function item(kind: ItemKind, title: string, extra: Partial<SurveyItem> = {}): SurveyItem {
  return { ...blankItem(kind), title, ...extra };
}

const section = (title: string, description = "") => item("section", title, { description });

const choice = (title: string, labels: string[], extra: Partial<SurveyItem> = {}) =>
  item("choice", title, {
    options: labels.map((label) => ({ id: newId("o"), label })),
    ...extra,
  });

