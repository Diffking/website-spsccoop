/** slug นี้เป็นของหน้าออกแบบอัตโนมัติหรือเปล่า */
export function designedPageOf(slug: string): DesignedPage | null {
  const clean = slug.replace(/^\/|\/$/g, "");
  return DESIGNED_PAGES.find((p) => p.slug === clean) ?? null;
}
