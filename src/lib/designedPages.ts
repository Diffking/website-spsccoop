/**
 * "หน้าออกแบบอัตโนมัติ" — หน้าที่ระบบจัดหน้าให้เองด้วยโค้ด ไม่ได้พิมพ์ HTML เอาเอง
 *
 * หน้าพวกนี้มีของที่พิมพ์เป็นเนื้อหาไม่ได้ เช่นแผนที่ที่กดนำทางได้ ปุ่มขอตำแหน่งปัจจุบัน
 * หรือคิวอาร์ที่สร้างสด ๆ ตอนกด จึงต้องเขียนเป็นเส้นทางในโค้ด (src/app/contact/)
 *
 * แต่เจ้าหน้าที่ยังต้องแก้ "ข้อมูล" ในหน้าได้ — ข้อมูลอยู่คนละที่กับหน้าเนื้อหาธรรมดา
 * ไฟล์นี้จึงเป็นสารบัญว่าหน้าไหนคือหน้าแบบนี้ และไปแก้อะไรได้ที่ไหน
 *
 * เส้นทางที่เขียนเป็นโค้ดมาก่อน /[...slug] เสมอ — หน้าเนื้อหาที่ตั้ง slug ชนกับรายการนี้
 * จะถูกหน้าโค้ดบังไว้ ไม่ขึ้นเว็บเอง (หน้าติดต่อเราดึงเนื้อหานั้นมาต่อท้ายให้แทน)
 *
 * ไฟล์นี้ไม่แตะฐานข้อมูล ใช้ได้ทั้งฝั่ง client และ server
 */

export type DesignedPage = {
  /** slug ที่หน้านี้ยึดไว้ — ตรงกับโฟลเดอร์ใน src/app/ */
  slug: string;
  /** ชื่อที่ใช้เรียกในหลังบ้าน */
  title: string;
  /** ที่อยู่หน้าจริงบนเว็บ */
  path: string;
  /** อธิบายสั้น ๆ ว่าหน้านี้ทำอะไรให้ */
  desc: string;
  /** ของที่ระบบจัดให้เอง — ไล่ให้เห็นว่าไม่ต้องไปพิมพ์เอง */
  features: string[];
  /** ไปแก้ข้อมูลของหน้านี้ได้ที่ไหน */
  settings: { href: string; label: string; hint: string }[];
  /** พิมพ์เนื้อหาเพิ่มต่อท้ายได้ไหม (ใช้ Page ที่ slug เดียวกัน) */
  acceptsExtraContent: boolean;
};

