export const UPDATING_DEFAULT_NOTE =
  "ขณะนี้เจ้าหน้าที่กำลังอัปเดตข้อมูลในหน้านี้ · กรุณากลับมาเยี่ยมชมใหม่ภายหลัง · ขออภัยในความไม่สะดวก";

export const UPDATING_NOTE_MAX = 300;

export function cleanUpdatingNote(input: unknown): string | null {
  if (typeof input !== "string") return null;
  return input.replace(/\s+/g, " ").trim().slice(0, UPDATING_NOTE_MAX) || null;
}
