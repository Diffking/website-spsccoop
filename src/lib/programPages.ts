/**
 * อ่านคำอธิบายที่แก้ไว้จากฐาน แล้วเติมส่วนที่ขาด
 * ⚠️ ช่องไหนว่างหรืออ่านไม่ออก **ต้องถอยกลับไปใช้ของตั้งต้น ไม่ใช่ปล่อยว่าง**
 * (หลักเดียวกับ fillIntro และ fillQuestions — แก้ค่าในฐานพลาดทีเดียวหน้าเว็บต้องไม่โล่ง)
 */
export function fillInterestIntro(raw: unknown): InterestIntro {
  const row = (raw ?? {}) as Record<string, unknown>;
  const text = (value: unknown, fallback: string) => String(value ?? "").trim() || fallback;
  const lines = (value: unknown, fallback: string[]) => {
    const list = Array.isArray(value)
      ? value.map((item) => String(item ?? "").trim()).filter(Boolean)
      : [];
    return list.length > 0 ? list : fallback;
  };

  return {
    heading: text(row.heading, DEFAULT_INTEREST_INTRO.heading),
    lead: text(row.lead, DEFAULT_INTEREST_INTRO.lead),
    paragraphs: lines(row.paragraphs, DEFAULT_INTEREST_INTRO.paragraphs),
    tips: lines(row.tips, DEFAULT_INTEREST_INTRO.tips),
  };
}

