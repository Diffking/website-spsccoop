const stripTags = (html: string) =>
  html
    .replace(/<br\s*\/?>/gi, " ")
    .replace(/<[^>]+>/g, "")
    .replace(/&nbsp;/g, " ")
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/\s+/g, " ")
    .trim();

/** ตัดคำนำหน้าที่ซ้ำกันทุกบรรทัดออก — บนการ์ดมีที่จำกัด ชื่อขึ้นต้นเหมือนกันหมดอ่านไม่ทัน */
const shortName = (name: string) =>
  name
    .replace(/^ระเบียบ\S*\s+ว่าด้วย\s*/, "")
    .replace(/^ระเบียบ\S*ว่าด้วย\s*/, "")
    .replace(/^แบบฟอร์ม\s*[-–—]?\s*/, "")
    .trim() || name;

/** อ่านแถวในตารางเอกสาร — แถวที่ไม่มีลิงก์หรือไม่มีชื่อ ถือว่าไม่ใช่เอกสาร ข้ามไป */
function readDocRows(block: string, kind: "reg" | "form"): PageDoc[] {
  const out: PageDoc[] = [];
  for (const row of block.matchAll(/<tr[^>]*>([\s\S]*?)<\/tr>/g)) {
    const href = row[1].match(/href="([^"]+)"/)?.[1];
    if (!href) continue;

    /*
      ชื่อเอกสารคือช่องที่ยาวที่สุดที่ไม่ใช่เลขลำดับ — ไม่ยึดว่าต้องเป็นช่องที่เท่าไหร่
      เผื่อวันหลังเจ้าหน้าที่เพิ่ม/สลับคอลัมน์ในตาราง (ทำได้เองใน EditUI)
      · ป้าย "New" ที่ครอบด้วย <span class="badge"> หลุดไปกับ stripTags อยู่แล้ว
    */
    const name = [...row[1].matchAll(/<td[^>]*>([\s\S]*?)<\/td>/g)]
      .map((cell) => stripTags(cell[1]))
      .filter((text) => text && !/^\d+\s*[.)]?$/.test(text))
      .sort((a, b) => b.length - a.length)[0];
    if (!name) continue;

    out.push({ kind, name, short: shortName(name), href, download: /\sdownload[\s>]/.test(row[1]) });
  }
  return out;
}

/**
 * ดึงตาราง "ระเบียบ" กับ "แบบฟอร์ม/เอกสารดาวน์โหลด" ออกจากเนื้อหา แล้วคืนส่วนที่เหลือ
 *
 * ที่ต้องดึงออกเพราะเอาไปแสดงใหม่แล้ว (บนการ์ด + รายการเต็มแบบพับเก็บ)
 * ถ้าปล่อยไว้จะเห็นของเดียวกันสองรอบ · หัวข้ออื่นที่ไม่ใช่สองอย่างนี้ (เช่น "สอบถามเพิ่มเติม")
 * ไม่แตะเลย คงอยู่ที่เดิมตามลำดับเดิม
 *
 * ⚠️ ระหว่างหัวข้อกับตารางมักมีย่อหน้าอธิบายคั่นอยู่ (หน้าเงินให้กู้/เงินรับฝากมีทุกอัน)
 * จึงต้องยอมให้มีอะไรคั่นได้ แต่ต้องไม่ใช่ `<h2>` อีกอันหรือ `<table>` อีกตาราง
 * ไม่งั้นมันจะกวาดข้ามหัวข้อถัดไปแล้วกลืนของที่ไม่เกี่ยวเข้ามาด้วย
 */
export function readDocTables(html: string): { tables: DocTable[]; rest: string } {
  const tables: DocTable[] = [];
  let rest = "";
  let last = 0;

  const block = /<h2[^>]*>([\s\S]*?)<\/h2>((?:(?!<h2|<table)[\s\S])*)(<table[\s\S]*?<\/table>)/g;
  for (const found of html.matchAll(block)) {
    const title = stripTags(found[1]);
    const kind = /ระเบียบ|หลักเกณฑ์/.test(title)
      ? "reg"
      : /ดาวน์โหลด|แบบฟอร์ม|เอกสาร/.test(title)
        ? "form"
        : null;
    if (!kind) continue;

    const docs = readDocRows(found[3], kind);
    if (docs.length === 0) continue;

    tables.push({ title, kind, docs });
    rest += html.slice(last, found.index);
    last = found.index + found[0].length;
  }

  return { tables, rest: (rest + html.slice(last)).trim() };
}

/**
 * หาเอกสารของ "เรื่องหนึ่ง" — ชื่อเรื่องเข้าหัวข้อไหน ก็ได้เอกสารที่เข้าหัวข้อนั้นไป
 *
 * เรียงระเบียบขึ้นก่อนแบบฟอร์มเสมอ ไม่ว่าตารางไหนจะอยู่บนอยู่ล่างในหน้า
 * (หน้าเงินให้กู้วางแบบฟอร์มไว้บน หน้าสวัสดิการวางระเบียบไว้บน — การ์ดต้องหน้าตาเดียวกัน)
 * เพราะลำดับที่ต้องอ่านคือ "ระเบียบว่าเข้าเกณฑ์ไหม" ก่อน แล้วค่อย "โหลดใบไปกรอก"
 */
export function matchDocs(name: string, docs: PageDoc[], topics: DocTopic[]): PageDoc[] {
  const topic = topics.find((t) => t.item.test(name));
  if (!topic) return [];
  return docs
    .filter((d) => topic.doc.test(d.name))
    .sort((a, b) => (a.kind === b.kind ? 0 : a.kind === "reg" ? -1 : 1));
}
