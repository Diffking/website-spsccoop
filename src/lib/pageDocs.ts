/** ระเบียบหรือแบบฟอร์มหนึ่งฉบับ */
export type PageDoc = {
  /** `reg` = ระเบียบ/หลักเกณฑ์ · `form` = แบบฟอร์มที่ต้องกรอกยื่น */
  kind: "reg" | "form";
  /** ชื่อเต็มตามที่เจ้าหน้าที่พิมพ์ไว้ในตาราง */
  name: string;
  /** ชื่อที่ตัดคำนำหน้าซ้ำ ๆ ออกแล้ว ("ระเบียบสหกรณ์ ว่าด้วย ", "แบบฟอร์ม - ") */
  short: string;
  href: string;
  /** ตารางไหนใส่ `download` ไว้ = กดแล้วโหลดลงเครื่องเลย ไม่เปิดอ่านในเบราว์เซอร์ */
  download: boolean;
};

/** ตารางเอกสารท้ายหน้าหนึ่งตาราง — เก็บไว้ให้ดูรายการเต็มได้ที่เดิม */
export type DocTable = {
  /** หัวข้อเดิมของตาราง เช่น "ระเบียบสวัสดิการ" "แบบฟอร์มด้านสินเชื่อ" */
  title: string;
  kind: "reg" | "form";
  docs: PageDoc[];
};

/** หัวข้อหนึ่งเรื่อง — `item` จับชื่อเรื่องบนการ์ด · `doc` จับชื่อเอกสารในตาราง */
export type DocTopic = { key: string; item: RegExp; doc: RegExp };

