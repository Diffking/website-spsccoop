  "เภสัชกร",
  "ศาสตราจารย์",
  "รองศาสตราจารย์",
  "ผู้ช่วยศาสตราจารย์",
  "ดร.",
  "นพ.",
  "พญ.",
  "ทพ.",
  "ภก.",
  "ผศ.",
  "รศ.",
