/**
 * ท่าเปลี่ยนเนื้อหาแบบ "ค่อย ๆ จางทับกัน" — ใช้ให้เหมือนกันทั้ง 4 อย่าง
 *
 * ⚠️ **ห้ามใช้ `mode="wait"` กับท่านี้** — `mode="wait"` จะรอให้ของเก่าจางหายจนหมด
 * ก่อนแล้วค่อยเอาของใหม่ขึ้น สายตาจึงเห็นเป็นวูบว่างหนึ่งจังหวะ = กระตุก
 * ปล่อยให้ AnimatePresence ทำงานโหมดปกติ (ของเก่ากับของใหม่อยู่พร้อมกันชั่วครู่)
 * แล้ววางทั้งคู่ให้ทับกันด้วย `gridArea: "1 / 1"` ในกรอบที่เป็น `grid`
 *
 * จังหวะข้างในจงใจให้เหลื่อมกันนิดเดียว ไม่ใช่จางพร้อมกันเป๊ะ:
 *   ของเก่าเริ่มจางทันที (เร็ว) · ของใหม่รอนิดนึงค่อยโผล่ (ช้ากว่า)
 * ทับกันแค่แวบเดียวพอไม่ให้เห็นช่องว่าง แต่ไม่ทับนานจนตัวหนังสือซ้อนกันจนอ่านไม่ออก
 */
export function fadeSwap(fade: number, reduce: boolean | null) {
  const d = reduce ? 0 : fade;
  return {
    initial: { opacity: 0 },
    animate: {
      opacity: 1,
      transition: { duration: d * 0.75, delay: d * 0.3, ease: "easeOut" as const },
    },
    exit: {
      opacity: 0,
      transition: { duration: d * 0.45, ease: "easeIn" as const },
    },
  };
}

