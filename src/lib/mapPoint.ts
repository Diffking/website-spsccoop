/**
 * อ่านพิกัดจากสิ่งที่คนก๊อปมาวาง
 *
 * ในทางปฏิบัติไม่มีใครก๊อป "7.012345,100.456789" มาตรง ๆ — ส่วนใหญ่ลากลิงก์จากกูเกิลแมป
 * ทั้งเส้นมาวาง ซึ่งพิกัดฝังอยู่หลัง @ หรือใน ?q= ตัวนี้ดึงเฉพาะตัวเลขออกมาให้
 *
 * ไม่ใช้ DOM ไม่แตะฐานข้อมูล ใช้ได้ทั้งฝั่ง client และ server
 */

/** ช่วงพิกัดที่เป็นไปได้จริงบนโลก — กันเลขที่บังเอิญหน้าตาเหมือนพิกัด */
const inRange = (lat: number, lng: number) =>
  Math.abs(lat) <= 90 && Math.abs(lng) <= 180 && !(lat === 0 && lng === 0);

/**
 * คืน "lat,lng" ที่สะอาดแล้ว — อ่านไม่ออกคืนค่าที่ใส่มาเดิม (ไม่ล้างของที่คนกำลังพิมพ์ทิ้ง)
 *
 * รับได้ทั้ง:
 *   7.012345,100.456789
 *   7.012345, 100.456789
 *   https://www.google.com/maps/place/.../@7.012345,100.456789,17z/...
 *   https://maps.google.com/?q=7.012345,100.456789
 */
export function parseMapPoint(input: string): string {
  const text = input.trim();
  if (!text) return "";

  // ลิงก์กูเกิลแมปเก็บพิกัดของกล้องไว้หลัง @ — เอาอันนี้ก่อนเพราะแม่นกว่า ?q= ที่อาจเป็นคำค้น
  const at = /@(-?\d{1,3}\.\d+),(-?\d{1,3}\.\d+)/.exec(text);
  const pair = at ?? /(-?\d{1,3}\.\d+)\s*,\s*(-?\d{1,3}\.\d+)/.exec(text);
  if (!pair) return text;

  const lat = Number(pair[1]);
  const lng = Number(pair[2]);
  return inRange(lat, lng) ? `${lat},${lng}` : text;
}
